// Minimal .docx writer (Word opens it natively): headings, paragraphs, bullets,
// a simple table and links. Packaged as an uncompressed ZIP, no dependencies.

export type Block =
  | { h: 1 | 2; text: string }
  | { p: string; muted?: boolean }
  | { li: string }
  | { table: string[][] } // first row is the header
  | { link: string; href: string };

const xmlEsc = (s: string) =>
  s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "");

const run = (text: string, props = "") =>
  text
    .split("\n")
    .map((line, i) => `${i ? "<w:r><w:br/></w:r>" : ""}<w:r>${props ? `<w:rPr>${props}</w:rPr>` : ""}<w:t xml:space="preserve">${xmlEsc(line)}</w:t></w:r>`)
    .join("");

function body(blocks: Block[]): { xml: string; links: string[] } {
  const links: string[] = [];
  const parts = blocks.map((b) => {
    if ("h" in b) return `<w:p><w:pPr><w:pStyle w:val="Heading${b.h}"/></w:pPr>${run(b.text)}</w:p>`;
    if ("li" in b) return `<w:p><w:pPr><w:pStyle w:val="ListBullet"/></w:pPr>${run(b.li)}</w:p>`;
    if ("p" in b) return `<w:p>${run(b.p, b.muted ? '<w:color w:val="6B7280"/>' : "")}</w:p>`;
    if ("link" in b) {
      links.push(b.href);
      return `<w:p><w:hyperlink r:id="rIdL${links.length}"><w:r><w:rPr><w:color w:val="1F4E79"/><w:u w:val="single"/></w:rPr><w:t xml:space="preserve">${xmlEsc(b.link)}</w:t></w:r></w:hyperlink></w:p>`;
    }
    const rows = b.table
      .map(
        (r, i) =>
          `<w:tr>${r
            .map((c) => `<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/></w:tcPr><w:p>${run(c, i === 0 ? "<w:b/>" : "")}</w:p></w:tc>`)
            .join("")}</w:tr>`,
      )
      .join("");
    const cols = Math.max(...b.table.map((r) => r.length));
    const grid = `<w:tblGrid>${`<w:gridCol w:w="${Math.floor(10080 / cols)}"/>`.repeat(cols)}</w:tblGrid>`; // required by the schema
    return `<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="5000" w:type="pct"/></w:tblPr>${grid}${rows}</w:tbl><w:p/>`;
  });
  return { xml: parts.join(""), links };
}

